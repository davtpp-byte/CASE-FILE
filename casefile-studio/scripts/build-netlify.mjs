/**
 * Build the Netlify publish directory from the committed, prebuilt frontend.
 *
 * No npm install is needed: web/assets/app.js and app.css are already built
 * and version-stamped. This script copies them into dist/ and generates the
 * Netlify routing/header files from build-time environment variables, so no
 * hostname or password is ever hard-coded in the repository.
 */
import { cpSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "dist");

const apiOrigin = (process.env.CASEFILE_API_ORIGIN || "").trim().replace(/\/+$/, "");
const user = (process.env.CASEFILE_USER || "").trim();
const password = (process.env.CASEFILE_PASSWORD || "").trim();

if (apiOrigin && !/^https:\/\/[a-z0-9.-]+(:\d+)?$/i.test(apiOrigin)) {
  throw new Error(
    "CASEFILE_API_ORIGIN must be an https:// host, e.g. https://casefile-studio.onrender.com",
  );
}
if ((user && !password) || (!user && password)) {
  throw new Error("Set BOTH CASEFILE_USER and CASEFILE_PASSWORD, or neither.");
}
if (user && (!/^[^\s:]+$/.test(user) || !/^[^\s:]+$/.test(password))) {
  throw new Error("CASEFILE_USER / CASEFILE_PASSWORD cannot contain spaces or colons.");
}

// Fresh publish directory: never ship stale redirect or auth headers.
rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
cpSync(join(root, "web/index.html"), join(out, "index.html"));
cpSync(join(root, "web/assets"), join(out, "assets"), { recursive: true });

const redirects = [
  "# Generated by scripts/build-netlify.mjs — do not edit by hand.",
];
if (apiOrigin) {
  // 200! = forced rewrite/proxy (status 200). The browser keeps the Netlify URL.
  redirects.push(
    `/api/*        ${apiOrigin}/api/:splat       200!`,
    `/media/*      ${apiOrigin}/media/:splat     200!`,
    `/exports/*    ${apiOrigin}/exports/:splat   200!`,
  );
} else {
  redirects.push(
    "# CASEFILE_API_ORIGIN was not set: static files only, API calls will fail.",
  );
}
redirects.push("/*            /index.html                    200");
writeFileSync(join(out, "_redirects"), redirects.join("\n") + "\n");

const headers = [
  "/*",
  "  X-Content-Type-Options: nosniff",
  "  Referrer-Policy: no-referrer",
  "  X-Frame-Options: SAMEORIGIN",
];
if (user) {
  // Netlify Basic-Auth (availability depends on the Netlify plan).
  headers.push(`  Basic-Auth: ${user}:${password}`);
}
headers.push(
  "",
  "/api/*",
  "  Cache-Control: no-store",
  "",
  "/media/*",
  "  Cache-Control: private, no-store",
  "",
  "/exports/*",
  "  Cache-Control: private, no-store",
);
writeFileSync(join(out, "_headers"), headers.join("\n") + "\n");

console.log(
  `Netlify dist/ ready. API proxy: ${apiOrigin || "(not set — static only)"}; ` +
    `Basic-Auth: ${user ? "enabled" : "disabled"}.`,
);
